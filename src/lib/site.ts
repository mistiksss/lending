export function frameSrc(index: number) {
  return site.film.framePath(index);
}

export function chapterOpacity(progress: number, start: number, end: number) {
  const fade = 0.025;
  if (progress < start || progress > end) return 0;
  if (progress < start + fade) return (progress - start) / fade;
  if (progress > end - fade) return (end - progress) / fade;
  return 1;
}
